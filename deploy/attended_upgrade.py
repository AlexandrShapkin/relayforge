"""Selector-only upgrade engine for a NEW independently reviewed attended package.

Not a deployment CLI. The package supplies the sealed, configured attended
activation backend (recovery scheduler, authenticated probes, lock and physical
terminal). Never point this at the frozen first-activation package. No package,
receipt, approval or health evidence is generated by this module.
"""
import argparse
import json
import os
import hashlib
import stat
import signal
import sys
import re
import time
import uuid

CANDIDATE = ('52387f09f661dd587c202e726430ceded44255ab',
             'f38f691e668fdd15d14a12f5794219957df686878fa52c8d243e4bd6842732c8')
BASELINE = ('4b3c0b7087d45707ca3fe2ae8d875c1ade6d2eaf',
            'a3bee8cfc3dd72cc26382af265dd6e84d4f34e7eb038c1202ab45ead8e6493f5')
ARTIFACT = 12583938383
WINDOW = 1200
MARGIN = 90


def require(ok, reason):
    if not ok:
        raise RuntimeError(reason)


class Upgrade:
    """Use only under backend.locked and a bounded process alarm.

    Backend is a freshly sealed attended_activation module, configured for this
    upgrade, with its transition.py dispatching recovery to this engine. Its
    invariant must preserve the exact installed units, root maps, credentials,
    grants, legacy guard and inventory. It must NOT use the initial activation's
    invariant/ready/activate/rollback or change those objects to make them match.
    Backend sealed() covers this engine, all support/probe code and evidence pins.
    """
    def __init__(self, backend, rollback_receipt, evidence):
        self.b = backend
        self.a = backend.a
        self.receipt = rollback_receipt
        self.evidence = evidence
        require((backend.COMMIT, backend.SHA) == CANDIDATE, 'candidate pin mismatch')
        require((backend.m.M['commit'], backend.m.M['baseline']) == BASELINE,
                'installed baseline pin mismatch')
        self.before = {'link': 'artifacts/' + '-'.join(BASELINE)}
        self.after = {'link': 'artifacts/' + '-'.join(CANDIDATE)}
        require(backend.BASE == self.before['link'] and backend.CAND == self.after['link'],
                'artifact path mismatch')
        self.current = backend.m.STORE / 'current'
        # previous is preserved verbatim; it is not the rollback authority.
        self.previous = backend.m.STORE / 'previous'
        self.previous_state = self.a.state(self.previous)

    def targets(self):
        return {self.previous: self.previous_state, self.current: self.after}

    def invariant(self):
        self.b.sealed()
        self.preserved()
        self.b.artifact(self.b.BASE, *BASELINE)
        self.b.artifact(self.b.CAND, *CANDIDATE)

    def preserved(self):
        """Verify a sealed hash/inventory snapshot; never store credential bodies."""
        self.a.regular(self.b.P / 'upgrade-preserved.json', limit=1024 * 1024)
        record = json.loads((self.b.P / 'upgrade-preserved.json').read_text())
        require(set(record) == {'roots', 'objects'}, 'preservation schema mismatch')
        home = self.b.m.H
        roots = [home / '.config/relayforge', home / '.config/tunnel-client',
                 self.b.UNITS, self.b.m.STORE / 'artifacts']
        require(record['roots'] == [str(p) for p in roots], 'preservation roots mismatch')
        # Generated attempt recovery objects are the sole inventory exception.
        # They must match our exact scheduler templates and durable journals.
        recovery = {}
        for directory in self.b.ATTEMPTS.iterdir():
            transaction = self.load(directory.name)
            for name, data in self.b.recovery_templates(
                    directory.name, transaction.doc['deadline']).items():
                recovery[str(self.b.UNITS / name)] = self.a.file_state(data, 0o600)
            timer = 'relayforge-activation-' + directory.name + '.timer'
            recovery[str(self.b.UNITS / 'timers.target.wants' / timer)] = {
                'link': str(self.b.UNITS / timer)}
        observed = {}
        def visit(path):
            self.a.ancestors(path.parent)
            meta = path.lstat()
            require(meta.st_uid == os.getuid(), 'preserved owner changed')
            if str(path) in recovery:
                require(self.a.state(path) == recovery[str(path)], 'recovery object changed')
                return
            if stat.S_ISDIR(meta.st_mode):
                require(not meta.st_mode & 0o022, 'unsafe preserved directory')
                observed[str(path)] = {'directory': stat.S_IMODE(meta.st_mode)}
                for child in path.iterdir():
                    visit(child)
            elif stat.S_ISLNK(meta.st_mode):
                observed[str(path)] = {'link': os.readlink(path)}
            else:
                require(stat.S_ISREG(meta.st_mode) and meta.st_nlink == 1
                        and not meta.st_mode & 0o022, 'unsafe preserved file')
                with self.b.m.artifact.opened(path) as (fd, before):
                    digest = hashlib.sha256()
                    while chunk := os.read(fd, 1024 * 1024):
                        digest.update(chunk)
                    after = os.fstat(fd)
                    require((before.st_size, before.st_mtime_ns, before.st_ctime_ns) ==
                            (after.st_size, after.st_mtime_ns, after.st_ctime_ns),
                            'preserved file changed during hashing')
                observed[str(path)] = {'sha256': digest.hexdigest(),
                                       'mode': stat.S_IMODE(meta.st_mode)}
        for root in roots:
            visit(root)
        require(observed == record['objects'], 'installed inventory changed')
        guard = self.b.UNITS / 'relayforge-local-recover.service.d/issue77-maintenance.conf'
        require(str(guard) in observed and b'ExecStart=/usr/bin/false' in guard.read_bytes(),
                'intentional legacy guard changed')
        for unit in self.b.m.M['units']:
            props = self.b.m.props(unit)
            require(props['NeedDaemonReload'] == 'no'
                    and props['FragmentPath'] == str(self.b.UNITS / unit),
                    'loaded unit differs from preserved disk state')
            expected = str(guard) if unit == 'relayforge-local-recover.service' else ''
            require(props['DropInPaths'] == expected, 'loaded drop-ins changed')
        require('/usr/bin/false' in self.b.m.props('relayforge-local-recover.service')['ExecStart'],
                'intentional legacy guard not loaded')

    def check(self):
        """Read-only, including on missing evidence. Caller holds read-only lock."""
        self.invariant()
        require(self.a.state(self.previous) == self.previous_state, 'previous selector changed')
        require(self.a.state(self.current) == self.before, 'baseline selector changed')
        # Required staged artifacts are verified in place. This engine never
        # stages, chmods, overwrites or removes an artifact.
        candidate = self.b.m.artifact.verify(
            self.b.m.STORE / self.b.CAND / 'relayforge-mcp',
            self.b.m.STORE / self.b.CAND / 'manifest.json', *CANDIDATE)
        baseline = self.b.m.artifact.verify(
            self.b.m.STORE / self.b.BASE / 'relayforge-mcp',
            self.b.m.STORE / self.b.BASE / 'manifest.json', *BASELINE)
        self.b.m.artifact.activation_plan(candidate, baseline, self.receipt)
        # Separate independently recorded provenance/fresh health evidence is
        # pinned by the sealed package. A historical filename proves nothing.
        proof = self.b.m.artifact.document(self.evidence)
        require(set(proof) == {'artifact_id', 'candidate', 'baseline', 'observed',
                               'expires', 'independent_review', 'recovery_test'},
                'independent evidence schema mismatch')
        require(type(proof['artifact_id']) is int and proof['artifact_id'] == ARTIFACT
                and proof['candidate'] == list(CANDIDATE)
                and proof['baseline'] == list(BASELINE)
                and proof['independent_review'] is True and proof['recovery_test'] is True,
                'independent provenance/recovery evidence required')
        now = time.time()
        require(type(proof['observed']) is int and type(proof['expires']) is int
                and 0 <= now - proof['observed'] <= 3600
                and now + WINDOW <= proof['expires'] <= proof['observed'] + 7200,
                'independent rollback evidence stale')
        require(self.b.m.command(['loginctl', 'show-user', str(os.getuid()),
                                  '-p', 'Linger', '--value']).strip() == 'yes',
                'independent user recovery requires existing lingering')
        self.b.m.systemctl('show', 'timers.target', '-p', 'LoadState')
        self.b.local_health(BASELINE[1], require_worker=True)
        self.a.directory(self.b.ATTEMPTS)
        # Never start another attempt over a pending/failed recovery.
        for path in self.b.ATTEMPTS.iterdir():
            old = self.load(path.name)
            require(old.doc['status'] in ('committed', 'rolled-back'),
                    'unfinished upgrade requires recovery')
        return {'candidate': candidate, 'rollback': baseline,
                'operator_approval_required': True, 'actions_performed': []}

    def load(self, attempt):
        require(isinstance(attempt, str) and re.fullmatch('[0-9a-f]{32}', attempt),
                'invalid attempt')
        transaction = self.a.Transaction(self.b.ATTEMPTS / attempt / 'journal.json', self.targets())
        doc = transaction.doc
        require(doc['id'] == attempt and doc.get('physical_owner_approved') is True
                and type(doc.get('created')) is int
                and doc.get('deadline') == doc['created'] + WINDOW
                and doc['status'] in ('pending', 'rolling-back', 'rolled-back', 'committed')
                and doc['targets'][str(self.current)]['before'] == self.before,
                'upgrade journal mismatch')
        row = doc['targets'][str(self.previous)]
        require(row['before'] == row['after'] == self.a.state(self.previous),
                'previous selector changed')
        return transaction

    def remaining(self, transaction):
        require(time.time() < transaction.doc['deadline'] - MARGIN, 'upgrade deadline expired')

    def activate(self, approve):
        """approve prompts a physical owner, bound to attempt + pins + deadline.

        Must run under the shared exclusive attended lock and WINDOW-bounded
        alarm. Recovery uses the same lock in a separate systemd process.
        """
        self.check()
        attempt = uuid.uuid4().hex
        created = int(time.time())
        authorization = {'attempt': attempt, 'candidate': CANDIDATE, 'baseline': BASELINE,
                         'deadline': created + WINDOW,
                         'scope': 'current selector; restart HTTP and tunnel; exact rollback'}
        require(approve(authorization) is True, 'physical owner denied upgrade')
        require(time.time() < created + 60, 'operator approval expired')
        # Recheck after human delay; stale selectors/credentials are blockers.
        self.check()
        directory = self.b.ATTEMPTS / attempt
        directory.mkdir(mode=0o700)
        self.a.sync(directory.parent)
        transaction = self.a.Transaction(directory / 'journal.json', self.targets(), True,
            metadata={'id': attempt, 'created': created, 'deadline': created + WINDOW,
                      'physical_owner_approved': True}, expected_before={self.current: self.before})
        try:
            # Existing durable per-attempt calendar scheduler, NOT the legacy
            # watchdog. arm verifies active timer and fsynced enablement link.
            self.b.arm(transaction)
            self.invariant()
            self.load(attempt)
            self.remaining(transaction)
            transaction.apply(self.current)
            self.b.m.systemctl('restart', *self.b.m.SERVICES)
            self.b.wait_health(CANDIDATE[1], require_worker=True)
            # Existing bounded physical-owner confirmation of independent
            # authenticated tunnel operations. HTTP active alone cannot accept.
            self.b.remote(transaction)
            self.remaining(transaction)
            self.b.wait_health(CANDIDATE[1], require_worker=True)
            self.invariant()
            self.load(attempt)
            transaction.commit()
        except BaseException:
            signal.alarm(150)  # Fresh bounded foreground rollback budget.
            # Commit durability guard is interpreted on reopen. A durable commit
            # must never be undone because disarming the timer later fails.
            self.recover(attempt, early=True)
            raise
        self.b.disarm(transaction)
        return attempt

    def recover(self, attempt, early=False):
        transaction = self.load(attempt)
        if transaction.doc['status'] in ('committed', 'rolled-back'):
            self.b.disarm(transaction)
            return
        require(early or time.time() >= transaction.doc['deadline'], 'recovery not due')
        self.invariant()
        transaction.validate_rollback()
        # Record rollback intent durably BEFORE restart/selector restoration.
        # If restoration/restart/health fails, leave the independent timer and
        # rolling-back journal intact for diagnosis/retry; never claim success.
        transaction.doc['status'] = 'rolling-back'
        transaction.save()
        transaction.rollback()
        self.b.m.systemctl('restart', *self.b.m.SERVICES)
        self.b.wait_health(BASELINE[1], require_worker=True)
        self.invariant()
        require(self.a.state(self.current) == self.before, 'rollback selector mismatch')
        transaction.doc['status'] = 'rolled-back'
        transaction.save()
        self.b.disarm(transaction)


def run(backend, rollback_receipt, evidence):
    """Entry point for a new sealed package's transition.py; never source auto-run.

    Configure backend with the upgrade preservation invariant and recovery
    dispatch before calling. Existing attended scheduler invokes transition.py
    recover --attempt ID, so it always reopens this exact engine after a crash.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('operation', choices=['check', 'activate', 'recover'])
    parser.add_argument('--attempt')
    args = parser.parse_args()
    backend.sealed()
    require(backend.m.M['uid'] == os.getuid(), 'wrong physical owner')
    def expired(signum, frame):
        raise TimeoutError('bounded upgrade deadline')
    signal.signal(signal.SIGALRM, expired)
    signal.signal(signal.SIGTERM, expired)
    signal.alarm(WINDOW - 30 if args.operation == 'activate' else 150)
    try:
        # No bootstrap in this engine: package/lock/attempt directories and
        # lingering must have been independently prepared and verified.
        with backend.locked(readonly=args.operation == 'check',
                            wait=args.operation == 'recover'):
            engine = Upgrade(backend, rollback_receipt, evidence)
            if args.operation == 'check':
                print(engine.check())
            elif args.operation == 'recover':
                engine.recover(args.attempt)
            else:
                require(sys.stdin.isatty() and sys.stdout.isatty(),
                        'physical terminal required')
                def approve(authorization):
                    print(authorization, flush=True)
                    phrase = 'UPGRADE ' + authorization['attempt']
                    return input('Physical owner only; type ' + phrase + ': ') == phrase
                engine.activate(approve)
    finally:
        signal.alarm(0)
